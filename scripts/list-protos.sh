#!/usr/bin/env bash
# Writes deps/protos.zig, the list of sdk-core .proto files that `zig build gen-proto` compiles.
# Run it after moving deps/sdk-core; scripts/check-core-version.sh fails if the list is stale.
# Usage: scripts/list-protos.sh [--check]
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
protos="deps/sdk-core/crates/protos/protos"

list() {
  echo "//! Generated by scripts/list-protos.sh. Do not edit."
  echo "//! The sdk-core .proto files compiled into src/proto by \`zig build gen-proto\`."
  echo ""
  echo "pub const root = \"$protos\";"
  echo ""
  echo "/// Directories passed to protoc with -I, relative to \`root\`."
  echo "pub const include_dirs = [_][]const u8{ \"api_upstream\", \"local\", \"testsrv_upstream\", \"\" };"
  echo ""
  echo "/// Files compiled, relative to \`root\`."
  echo "pub const files = [_][]const u8{"
  (cd "$root/$protos" && find api_upstream/temporal local testsrv_upstream google/rpc grpc -name '*.proto' | LC_ALL=C sort) |
    sed 's|.*|    "&",|'
  echo "};"
}

if [ "${1:-}" = "--check" ]; then
  if ! diff <(list) "$root/deps/protos.zig" >/dev/null; then
    echo "deps/protos.zig is stale. Run scripts/list-protos.sh" >&2
    exit 1
  fi
  echo "deps/protos.zig is current"
else
  list > "$root/deps/protos.zig"
  echo "wrote deps/protos.zig ($(grep -c '\.proto",' "$root/deps/protos.zig") files)"
fi
