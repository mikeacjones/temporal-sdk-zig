#!/usr/bin/env bash
# Writes src/proto.zig, which exposes every generated package under src/proto as a nested
# namespace named after its proto package (temporal.api.common.v1, coresdk.workflow_activation).
# `zig build gen-proto` runs this after protoc. A package that also has sub-packages (coresdk)
# exposes its own file as `<name>.self`.
# Usage: scripts/gen-proto-index.sh
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/src/proto.zig"

# Zig keywords must be written as @"name".
keywords=" addrspace align allowzero and anyframe anytype asm break callconv catch comptime const continue defer else enum errdefer error export extern fn for if inline linksection noalias noinline nosuspend opaque or orelse packed pub resume return struct suspend switch test threadlocal try union unreachable var volatile while "
ident() { if [[ "$keywords" == *" $1 "* ]]; then printf '@"%s"' "$1"; else printf '%s' "$1"; fi; }

files=$(cd "$root/src/proto" && find . -name '*.pb.zig' | sed 's|^\./||; s|\.pb\.zig$||' | LC_ALL=C sort)

{
  echo "//! Generated by scripts/gen-proto-index.sh. Do not edit."
  echo "//! Zig types for the Temporal API, the sdk-core interface, and their dependencies,"
  echo "//! generated from deps/sdk-core protos with zig-protobuf."
  echo ""
  prev=()
  for f in $files; do
    IFS=/ read -ra parts <<< "$f"
    # Close namespaces that are not shared with this path.
    common=0
    while [ $common -lt ${#prev[@]} ] && [ $common -lt $((${#parts[@]} - 1)) ] && [ "${prev[$common]}" = "${parts[$common]}" ]; do
      common=$((common + 1))
    done
    for ((i = ${#prev[@]} - 1; i >= common; i--)); do
      printf '%*s};\n' $((i * 4)) ""
    done
    prev=("${prev[@]:0:$common}")
    # A directory with the same name as this file means the package has sub-packages.
    last=$((${#parts[@]} - 1))
    for ((i = common; i < last; i++)); do
      printf '%*spub const %s = struct {\n' $((i * 4)) "" "$(ident "${parts[$i]}")"
      prev+=("${parts[$i]}")
    done
    if [ -d "$root/src/proto/$f" ]; then
      printf '%*spub const %s = struct {\n' $((last * 4)) "" "$(ident "${parts[$last]}")"
      printf '%*spub const self = @import("proto/%s.pb.zig");\n' $(((last + 1) * 4)) "" "$f"
      prev+=("${parts[$last]}")
    else
      printf '%*spub const %s = @import("proto/%s.pb.zig");\n' $((last * 4)) "" "$(ident "${parts[$last]}")" "$f"
    fi
  done
  for ((i = ${#prev[@]} - 1; i >= 0; i--)); do
    printf '%*s};\n' $((i * 4)) ""
  done
} > "$out"
echo "wrote src/proto.zig"
